// Renders the official Figma UI3 icons shipped by @create-figma-plugin/ui
// (Preact components) to plain SVG strings once, so the plugin UI can use
// them without Preact. Output: ui/icons.js. Run: npm run icons
import { writeFile } from 'node:fs/promises';
import { h } from 'preact';
import { renderToString } from 'preact-render-to-string';

// UI key -> icon file (without the "-<size>.js" suffix); "16/" picks the 16px set.
const ICONS = {
  text: 'icon-text-small',
  straight: 'icon-line-small',
  chevron: 'icon-chevron-down',
  more: 'icon-more',
  adjust: 'icon-adjust-small',
  strokeWeight: 'icon-stroke-weight',
  corners: 'icon-corners',
  gap: 'icon-spacing-horizontal-small',
  fontSize: 'icon-text-font-size',
  capArrow: 'icon-stroke-line-arrow',
  capTriangle: 'icon-stroke-triangle-arrow',
  capCircle: 'icon-stroke-circle-arrow',
  capDiamond: 'icon-stroke-diamond-arrow',
  strokeSolid: 'icon-stroke-solid',
  strokeDash: 'icon-stroke-dash',
  plus: 'icon-plus',
  minus: 'icon-minus',
  swap: 'icon-swap-small',
  trash: 'icon-trash',
  target: 'icon-search-small',
  interaction: 'icon-interaction-click-small',
  link: 'icon-link-connected',
  warning: 'icon-warning-small',
};

const lines = [];
for (const [key, file] of Object.entries(ICONS)) {
  // The package does not export this subpath, so load the file directly.
  const [size, name] = file.startsWith('16/') ? ['16', file.slice(3)] : ['24', file];
  const mod = await import(new URL(`../node_modules/@create-figma-plugin/ui/lib/icons/icon-${size}/${name}-${size}.js`, import.meta.url));
  const Icon = Object.values(mod)[0];
  const html = renderToString(h(Icon, {}));
  const svg = html.match(/<svg[\s\S]*<\/svg>/);
  if (!svg) throw new Error(`No <svg> rendered for ${file}`);
  lines.push(`  ${key}: ${JSON.stringify(svg[0].replace(/\s+xmlns="[^"]*"/, ' xmlns="http://www.w3.org/2000/svg"'))},`);
}

const out = `// Generated by scripts/extract-icons.mjs from @create-figma-plugin/ui (icon-24 / icon-16).
// Do not edit by hand.
export const ICONS = {
${lines.join('\n')}
};
`;
await writeFile(new URL('../ui/icons.js', import.meta.url), out);
console.log(`ui/icons.js: ${Object.keys(ICONS).length} icons`);
