export const MESSAGES = en;

export function translator(base = {}) {
  return (key, vars = {}) => {
    const all = { ...base, ...vars };
    return String(en[key] ?? key).replace(/\{(\w+)\}/g, (_, k) => (k in all ? String(all[k]) : ''));
  };
}

// '1 connector' / '3 connectors': key.one for 1, key.other otherwise.
export const plural = (t, key, n, vars = {}) => t(`${key}.${n === 1 ? 'one' : 'other'}`, { n, ...vars });
